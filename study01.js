// คำสั่ง console.log() สำหรับ dev โดยเฉพาะ ***
// ใช้แสดงข้อมูลใดๆที่หน้าต่าง Terminal (ใน vs code)/Console (ใน browser)
// String
console.log("AAAAAA");
console.log("BBBBBB");
console.log(`CCCCCC`); //Alt+9+6 ตัวหนอนอ่ะ, กดค้างไว้ ``
// Number
console.log(111111); //integer
console.log(222222.2222); //float
console.log(true); //boolean
console.log(false); //boolean
// Array ***
console.log([100, 200, 300, 400]);
console.log([100, 200, true, 'ABCD', 23.879, 'SAU']);
// Object ***
console.log(
    {
        //key : value
        name: "ToT",
        age: 25,
        gender: "Male",
        isStudent: true,
        food: ["KFC", "Mcdonald", "Pizza",],
        address: {
            city: "Bangkok",
            country: "Thailand",
        },
    }
);
//Undefined
console.log(undefined);
// Null
console.log(null);
// NaN (Not a Number)
console.log(NaN);
console.log("Sombat" / 55);
